def main() -> None:
    st.markdown(CSS, unsafe_allow_html=True)
    extractor = get_extractor()

    with st.sidebar:
        st.markdown("### Settings")
        backend_default = semantic_backend_available()
        backend = st.selectbox(
            "Semantic backend",
            ["auto", "lsa"],
            help=(
                "'auto' uses the sentence-transformer model when installed and falls "
                "back to Latent Semantic Analysis otherwise. 'lsa' forces the "
                "dependency-free fallback."
            ),
        )
        st.markdown(
            f'<div class="rjm-sub">Available: '
            f'{"sentence-transformers" if backend_default == "st" else "LSA fallback"}</div>',
            unsafe_allow_html=True,
        )

        st.markdown("### Scoring weights")
        st.markdown(
            '<div class="rjm-sub">Defaults are documented project assumptions, not '
            "tuned optimums. Move them and the score updates.</div>",
            unsafe_allow_html=True,
        )
        weights = (
            st.slider("Required skills", 0.0, 1.0, 0.40, 0.05),
            st.slider("Preferred skills", 0.0, 1.0, 0.15, 0.05),
            st.slider("Semantic similarity", 0.0, 1.0, 0.25, 0.05),
            st.slider("TF-IDF similarity", 0.0, 1.0, 0.10, 0.05),
            st.slider("Experience", 0.0, 1.0, 0.05, 0.05),
            st.slider("Education", 0.0, 1.0, 0.05, 0.05),
        )
        total = sum(weights)
        if abs(total - 1.0) > 0.001:
            st.info(f"Weights total {total:.2f}; they are normalised before scoring.")

        st.markdown("### Score bands")
        weak_max = st.slider("Weak up to", 0, 100, 39)
        moderate_max = st.slider("Moderate up to", weak_max, 100, max(69, weak_max))
        strong_max = st.slider("Strong up to", moderate_max, 100, max(84, moderate_max))

        st.divider()
        st.markdown(
            f'<div class="rjm-sub">Skill database: {len(extractor.vocab)} skills, '
            f"{len(extractor.vocab.alias_targets)} aliases</div>",
            unsafe_allow_html=True,
        )

    st.title("Resume-Job Matcher")
    st.markdown(
        '<p class="rjm-lede">Compare a resume against a job description and see which '
        "skills are missing. Built with traditional and semantic NLP: no language model "
        "is involved, so every figure below is computed from the extracted text and is "
        "reproducible.</p>",
        unsafe_allow_html=True,
    )

    left, right = st.columns(2, gap="large")
    with left:
        resume_text = document_input("Resume", "resume", SAMPLE_RESUMES_DIR, "01")
    with right:
        job_text = document_input("Job description", "job", SAMPLE_JOBS_DIR, "02")

    st.markdown('<h2><span class="rjm-step">03</span>Analyse</h2>', unsafe_allow_html=True)
    ready = bool(resume_text.strip() and job_text.strip())
    if not ready:
        st.markdown(
            '<div class="rjm-sub">Add a resume and a job description above. '
            'Pick "Use a sample" on both sides for a quick look.</div>',
            unsafe_allow_html=True,
        )
    analyse = st.button("Analyse match", type="primary", disabled=not ready)

    if not analyse:
        return

    thresholds = MatchThresholds(float(weak_max), float(moderate_max), float(strong_max))
    if backend == "auto" and backend_default == "st":
        warm_semantic_model(Settings().semantic_model_name)

    with st.spinner("Extracting skills, comparing text and scoring..."):
        try:
            report = run_analysis(
                resume_text, job_text, weights,
                (float(weak_max), float(moderate_max), float(strong_max)), backend,
            )
        except Exception:  # pragma: no cover - UI safety net
            st.error(
                "Something went wrong during the analysis. Try a different file, or "
                "paste the text directly."
            )
            st.stop()

    for warning in report.warnings:
        st.warning(warning)

    st.divider()
    render_verdict(report, thresholds)

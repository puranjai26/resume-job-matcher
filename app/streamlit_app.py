@st.cache_resource(show_spinner=False)
def get_extractor() -> SkillExtractor:
    """Load the skill vocabulary once and share it across sessions."""
    return SkillExtractor(load_skill_vocabulary())


@st.cache_resource(show_spinner="Loading the semantic model (first run only)...")
def warm_semantic_model(model_name: str) -> str:
    """Load the sentence-transformer model once, before the first analysis."""
    from src.similarity import load_semantic_model

    return "sentence-transformers" if load_semantic_model(model_name) is not None else "lsa"


@st.cache_data(show_spinner=False)
def list_samples(directory: str) -> dict[str, str]:
    """Read the bundled sample documents."""
    samples: dict[str, str] = {}
    for path in sorted(Path(directory).glob("*.txt")):
        samples[path.stem.replace("_", " ").title()] = path.read_text(encoding="utf-8")
    return samples


@st.cache_data(show_spinner=False, max_entries=32)
def run_analysis(
    resume_text: str,
    job_text: str,
    weights: tuple[float, ...],
    thresholds: tuple[float, float, float],
    backend: str,
) -> MatchReport:
    """Run the pipeline. Cached so re-rendering does not recompute the match."""
    settings = Settings(
        weights=ScoringWeights(*weights),
        thresholds=MatchThresholds(*thresholds),
        semantic_backend=backend,
    )
    return match_resume_to_job(
        resume_text, job_text, settings=settings, extractor=get_extractor()
    )


